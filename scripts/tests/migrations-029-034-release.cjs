'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const expected=['029_commercial_tariffs.sql','030_residential_survey.sql','031_quote_decisions.sql','032_service_contracts.sql','033_service_execution.sql','034_service_delivery.sql'];
const migrations=fs.readdirSync(path.join(root,'apps/api/migrations')).filter(x=>/^0(2[9]|3[0-4])_/.test(x)).sort();
assert.deepEqual(migrations,expected);
const qa=read('scripts/migrar-bonaire-qa-029-034.ps1');
assert.match(qa,/energia-vital-qa-db/);
assert.match(qa,/MIGRAR_SOLO_QA_029_034/);
assert.match(qa,/34\/34/);
assert.doesNotMatch(qa,/energia-vital-db --remote|wrangler deploy|pages deploy|r2 object put/);
const backup=read('scripts/respaldo-d1-029-034.ps1');
assert.match(backup,/28 -or \[int\]\$r\.last_id -ne 28/);
assert.match(backup,/--crear-28/);
assert.match(backup,/Remove-Item -LiteralPath \$sql -Force/);
assert.doesNotMatch(backup,/migrations apply|wrangler deploy|pages deploy|r2 object put/);
const usb=read('scripts/verificar-respaldo-usb-029-034.ps1');
for(const s of ['Get-Partition','Get-Disk','BusType','Get-FileHash','--verificar-28'])assert.ok(usb.includes(s));
const prod=read('scripts/migrar-bonaire-029-034.ps1');
for(const s of ['energia-vital-qa-db','energia-vital-db','MIGRAR_BONAIRE_029_034_CON_RESPALDO_USB','--verificar-28','migrations apply'])assert.ok(prod.includes(s));
assert.match(prod,/qa\.total -ne 34/);
assert.match(prod,/prod\.total -ne 28/);
assert.match(prod,/BusType/);
assert.doesNotMatch(prod,/wrangler deploy|pages deploy|r2 object put/);
const worker=read('scripts/publicar-solo-worker-bonaire.ps1');
assert.match(worker,/r\.total -ne 34/);
assert.match(worker,/r\.residential_flow -ne 9/);
const pages=read('scripts/pages-publicacion-controlada.ps1');
assert.match(pages,/\$total -ne 34 -or \$last -ne 34/);
const deploy=read('.github/workflows/deploy.yml');
assert.match(deploy,/Number\(row\?\.migrations\) !== 34/);
assert.match(deploy,/count !== 24/);
console.log('PASS release 029-034: QA first, production backup restored from separate USB, schema gates 34/34, no implicit deploy.');
