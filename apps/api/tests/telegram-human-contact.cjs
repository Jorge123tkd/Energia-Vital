const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),ts=require('typescript');
const source=fs.readFileSync(path.resolve(__dirname,'../src/telegram-human-contact.ts'),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};new Function('module','exports',js)(mod,mod.exports);
const {parsePublishedSalesManagers,formatHumanWhatsAppReply,humanWhatsAppReply}=mod.exports;
const one=JSON.stringify([{name:'Gestor Ejemplo',phone:'+53 5 123 4567'}]);
const many=JSON.stringify([{name:'Gestora A',phone:'+53 5 123 4567'},{name:'Gestor B',phone:'+53 5 765 4321'}]);
assert.equal(parsePublishedSalesManagers(one).length,1);
assert.equal(parsePublishedSalesManagers(many).length,2);
assert.equal(parsePublishedSalesManagers('not json').length,0);
const single=formatHumanWhatsAppReply(one);
assert.equal(single.buttons.length,1);
assert.equal(single.buttons[0].text,'💬 Gestor Ejemplo');
assert.match(single.buttons[0].url,/^https:\/\/wa\.me\/5351234567\?text=/);
assert.doesNotMatch(single.reply,/wa\.me|https?:\/\/|5351234567|energia-vital-web/);
const multiple=formatHumanWhatsAppReply(many);
assert.equal(multiple.buttons.length,2);
assert.equal(multiple.buttons[0].text,'💬 Gestora A');
assert.equal(multiple.buttons[1].text,'💬 Gestor B');
assert.match(multiple.buttons[1].url,/^https:\/\/wa\.me\/5357654321\?text=/);
assert.doesNotMatch(multiple.reply,/wa\.me|https?:\/\/|5357654321/);
const dup=JSON.stringify([{name:'A',phone:'+53 5 123 4567'},{name:'B',phone:'5351234567'},{name:'C',phone:'https://evil.example'}]);
assert.equal(parsePublishedSalesManagers(dup).length,1);
assert.equal(formatHumanWhatsAppReply('[]').buttons.length,0);
assert.doesNotMatch(formatHumanWhatsAppReply('[]').reply,/https?:\/\//);
(async()=>{
  const sql=[],db={prepare(s){sql.push(s);return {first:async()=>({value:many})}}};
  assert.deepEqual(await humanWhatsAppReply(db),multiple);
  assert.match(sql[0],/key='sales_managers'/);
  const failure=await humanWhatsAppReply({prepare(){throw Error('DB unavailable')}});
  assert.equal(failure.buttons.length,0);
  assert.match(failure.reply,/no puedo consultar/);
  assert.doesNotMatch(failure.reply,/https?:\/\//);
  console.log('PASS telegram-human-contact: botones inline, gestores y enlaces ocultos');
})().catch(e=>{console.error(e);process.exitCode=1;});
