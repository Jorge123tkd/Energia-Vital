'use strict';
const assert=require('node:assert/strict');
const {summarize,required}=require('./remote-inventory-schema.cjs');
const all=[...required,'refresh_hash'];
const good=summarize([{results:all.map(name=>({name}))}]);
assert.equal(good.ready,true);
assert.equal(good.presentCount,required.length);
assert.equal(good.refreshColumnPresent,true);
const legacy=summarize([{results:required.map(name=>({name}))}]);
assert.equal(legacy.ready,false);
assert.equal(legacy.refreshColumnPresent,false);
assert.deepEqual(legacy.missing,[]);
const absent=summarize([{results:all.filter(name=>name!=='customers').map(name=>({name}))}]);
assert.equal(absent.ready,false);
assert.deepEqual(absent.missing,['customers']);
assert.throws(()=>summarize([{results:[{name:'password_hash'}]}]),/Metadato no esperado/);
assert.throws(()=>summarize([{results:[{email:'test@example.invalid'}]}]),/Metadato no esperado/);
assert.throws(()=>summarize({results:{name:'auth_sessions'}}),/Formato D1/);
console.log('PASS D1 metadata-only readiness: full, missing migration, missing table and malformed input');